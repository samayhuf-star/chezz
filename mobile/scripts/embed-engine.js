// Copies the shared engine into the app and embeds it as a string for the hidden WebView worker.
const fs=require('fs'),path=require('path');
const src=fs.readFileSync(path.join(__dirname,'../../engine.js'),'utf8');
if(src.includes('</script>'))throw new Error('engine contains </script>');
fs.writeFileSync(path.join(__dirname,'../src/engine.js'),src);
fs.writeFileSync(path.join(__dirname,'../src/engineSource.js'),'// generated by scripts/embed-engine.js\nmodule.exports = '+JSON.stringify(src)+';\n');
console.log('engine embedded',src.length);
