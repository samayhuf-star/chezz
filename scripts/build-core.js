// Generates everything that is derived from core/ and the Stockfish npm package:
//   public/core.js            core + chess.js for the web app (global ChezzCore)
//   public/sf/                Stockfish worker script + wasm, served as static files
//   src/sf-factory.mjs        Stockfish loader as an ES module for the Cloudflare Worker
//   src/sf.wasm               the same wasm, imported by the Worker
//   mobile/src/core.js        core + chess.js for the Expo app
//   mobile/src/sfAssets.js    Stockfish loader + wasm (base64) for the app's hidden WebView
// Run: node scripts/build-core.js   (after changing core/ or upgrading the stockfish package)
const fs = require('fs'), path = require('path'), esbuild = require('esbuild');
const root = path.join(__dirname, '..'), bin = path.join(root, 'node_modules/stockfish/bin');
const NAME = 'stockfish-19-lite-single';
const glue = fs.readFileSync(path.join(bin, NAME + '.js'), 'utf8'), wasm = fs.readFileSync(path.join(bin, NAME + '.wasm'));
const out = (f, data) => { fs.mkdirSync(path.dirname(path.join(root, f)), { recursive: true }); fs.writeFileSync(path.join(root, f), data); console.log(f, (data.length / 1024).toFixed(0) + ' KB'); };

// The loader is `!function(){function e(){...factory...} <environment dispatch> }()`. Keep only function e.
const start = glue.indexOf('function e(){'), marker = '"undefined"!=typeof self&&"worker"===self.location.hash.split(",")[1]';
let end = glue.indexOf('}' + marker); if (end < 0) end = glue.lastIndexOf('}', glue.indexOf('em-pthread'));
if (start < 0 || end < 0) throw new Error('stockfish loader layout changed; update scripts/build-core.js');
const banner = glue.slice(0, glue.indexOf('!function(){')), fnE = glue.slice(start, end + 1);
// Environment globals are shadowed so the loader takes its plain path: no Node fs, no fetch, no worker location.
out('src/sf-factory.mjs', '// generated by scripts/build-core.js from the stockfish npm package (GPLv3)\n' + banner +
  'const env = { TextDecoder: globalThis.TextDecoder, name: "" };\n' +
  'export default (function (globalThis, global, process, fetch, self, document, window, module, exports, define) {\n' + fnE + '\nreturn e();\n})(env);\n');
out('src/sf.wasm', wasm);
out('public/sf/' + NAME + '.js', glue); out('public/sf/' + NAME + '.wasm', wasm);
out('public/sf/COPYING.txt', fs.readFileSync(path.join(root, 'node_modules/stockfish/Copying.txt')));
if (glue.includes('</script>')) throw new Error('loader contains </script>');
out('mobile/src/sfAssets.js', '// generated by scripts/build-core.js from the stockfish npm package (GPLv3)\nmodule.exports = { GLUE: ' + JSON.stringify(glue) + ', WASM_B64: "' + wasm.toString('base64') + '" };\n');

const common = { entryPoints: [path.join(root, 'core/index.js')], bundle: true, write: false, target: 'es2019', legalComments: 'inline' };
const head = '// generated by scripts/build-core.js from core/ and chess.js (BSD-2-Clause, (c) Jeff Hlywa)\n';
out('public/core.js', head + esbuild.buildSync({ ...common, format: 'iife', globalName: 'ChezzCore', minify: true }).outputFiles[0].text);
out('mobile/src/core.js', head + '/* eslint-disable */\n' + esbuild.buildSync({ ...common, format: 'cjs', platform: 'neutral', mainFields: ['main'] }).outputFiles[0].text);
